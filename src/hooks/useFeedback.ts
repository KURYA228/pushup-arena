/** Shared feedback settings plus the cues bound to them. */
export function useFeedback() {
  const [prefs, setPrefs] = useState<FeedbackPrefs>(loadFeedbackPrefs);

  useEffect(() => {
    installAudioUnlock();
  }, []);

  const update = useCallback((patch: Partial<FeedbackPrefs>) => {
    setPrefs((p) => {
      const next = { ...p, ...patch };
      saveFeedbackPrefs(next);
      return next;
    });
  }, []);

  return useMemo(
    () => ({
      prefs,
      setSound: (on: boolean) => update({ sound: on }),
      setVibration: (on: boolean) => update({ vibration: on }),
      canVibrate: vibrationSupported(),
      /** `sound` lets a stage ask for its own rep cue; left out, the ordinary beep plays. */
      rep: (crit = false, sound?: HitSound, double?: boolean) => playRep(prefs, crit, sound, double),
      bossDefeat: () => playBossDefeat(prefs),
      bossEncounter: (line?: Line) => playBossEncounter(prefs, line),
      levelUp: () => playLevelUp(prefs),
      rankUp: () => playRankUp(prefs),
      rushEnd: () => playRushEnd(prefs),
      purchase: () => playPurchase(prefs),
      feePaid: () => playFeePaid(prefs),
      woodCrack: () => playWoodCrack(prefs),
      poof: () => playPoof(prefs),
      iceCrack: () => playIceCrack(prefs),
      iceShatter: () => playIceShatter(prefs),
      giggle: () => playGiggle(prefs),
      fizzle: () => playFizzle(prefs),
      slipper: () => playSlipper(prefs),
      dizzy: () => playDizzy(prefs),
      cardFlip: () => playCardFlip(prefs),
      cackle: () => playCackle(prefs),
      squirt: () => playSquirt(prefs),
      boing: () => playBoing(prefs),
      bang: () => playBang(prefs),
      xpOrbs: () => playXpOrbs(prefs),
      orb: () => playOrb(prefs),
      xpLevel: () => playXpLevel(prefs),
      slabLand: () => playSlabLand(prefs),
      footstep: () => playFootstep(prefs),
      slabBreak: () => playSlabBreak(prefs),
      explosion: () => playExplosion(prefs),
      arrow: () => playArrow(prefs),
      creeperHiss: () => playCreeperHiss(prefs),
      dragonDeath: () => playDragonDeath(prefs),
      portal: () => playPortal(prefs),
      roar: () => playRoar(prefs),
      teleport: () => playTeleport(prefs),
      fanfare: () => playFanfare(prefs),
      gusli: () => playGusli(prefs),
      quill: () => playQuill(prefs),
      bells: () => playBells(prefs),
      salute: () => playSalute(prefs),
      sonicCannon: () => playSonicCannon(prefs),
      starbolts: () => playStarbolts(prefs),
      communicator: () => playCommunicator(prefs),
      staffBlock: () => playStaffBlock(prefs),
      screech: () => playScreech(prefs),
      cameraStatic: () => playStatic(prefs),
      sixAm: () => playSixAm(prefs),
      yay: () => playYay(prefs),
      /** Starts Freddy's music box looping; call what it returns to stop it. */
      musicBox: () => startMusicBox(prefs),
      slide: () => playSlide(prefs),
      shieldClank: () => playShieldClank(prefs),
      shieldBlock: () => playShieldBlock(prefs),
      ninjaVanish: () => playNinjaVanish(prefs),
      soupDinner: () => playSoupDinner(prefs),
      soupCool: () => playSoupCool(prefs),
      laserVolley: () => playLaserVolley(prefs),
      mousers: () => playMousers(prefs),
      cowabunga: () => playCowabunga(prefs),
      elixirHeal: () => playElixirHeal(prefs),
      towerFall: () => playTowerFall(prefs),
      mimimi: () => playMimimi(prefs),
      megaKnight: (landAt: number) => playMegaKnight(prefs, landAt),
      gliderPass: () => playGliderPass(prefs),
      pumpkinBlast: () => playPumpkinBlast(prefs),
      thwip: () => playThwip(prefs),
      chariot: (dur: number) => playChariot(prefs, dur),
      lionGag: (roarAt: number, meowAt: number) => playLionGag(prefs, roarAt, meowAt),
      shutters: (count: number, over: number) => playShutters(prefs, count, over),
      arrowVolley: (landAt: number) => playArrowVolley(prefs, landAt),
      spartanCry: (beats: number[]) => playSpartanCry(prefs, beats),
      crowned: (at: number) => playCrowned(prefs, at),
      kiryukhaTalk: (intoFight: boolean) => startKiryukhaTalk(prefs, intoFight),
      goblinBoom: (boomAt: number) => playGoblinBoom(prefs, boomAt),
      skidysh: (atSec: number, belly?: boolean) => playSkidysh(prefs, atSec, belly),
      bellyBump: () => playBellyBump(prefs),
      kungFuHit: () => playKungFuHit(prefs),
      droneBlip: (n: number) => playDroneBlip(prefs, n),
      stringSnap: (snapAt: number) => playStringSnap(prefs, snapAt),
      mjolnir: (strikeAt: number) => playMjolnir(prefs, strikeAt),
      repulsor: (fireAt: number) => playRepulsor(prefs, fireAt),
      shieldThrow: (hitAt: number) => playShieldThrow(prefs, hitAt),
      nom: () => playNom(prefs),
      fireworkChair: (burstAt: number) => playFireworkChair(prefs, burstAt),
      scroll: () => playScroll(prefs),
      wuxi: (boomAt: number) => playWuxi(prefs, boomAt),
    }),
    [prefs, update],
  );
}

export type Feedback = ReturnType<typeof useFeedback>;
